// Função global t() — retorna tradução
window.t = function(chave) {
  var lang = window.idiomaAtual || 'pt';
  return (window.TRADUCOES[lang] && window.TRADUCOES[lang][chave]) || chave;
};

// Aplica traduções em TODOS os elementos [data-i18n]
window.aplicarTraducoes = function() {
  var lang = window.idiomaAtual || 'pt';
  var dict = window.TRADUCOES[lang];
  if (!dict) return 0;

  var aplicados = 0;

  // 1) Texto
  document.querySelectorAll('[data-i18n]').forEach(function(el) {
    var chave = el.getAttribute('data-i18n');
    var trad = dict[chave];
    if (trad !== undefined) {
      el.textContent = trad;
      aplicados++;
    }
  });

  // 2) Placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach(function(el) {
    var chave = el.getAttribute('data-i18n-placeholder');
    if (dict[chave]) el.placeholder = dict[chave];
  });

  // 3) Title
  document.querySelectorAll('[data-i18n-title]').forEach(function(el) {
    var chave = el.getAttribute('data-i18n-title');
    if (dict[chave]) el.title = dict[chave];
  });

  // 4) HTML
  document.querySelectorAll('[data-i18n-html]').forEach(function(el) {
    var chave = el.getAttribute('data-i18n-html');
    if (dict[chave]) { el.innerHTML = dict[chave]; aplicados++; }
  });

  // 5) Botão de idioma (rodapé)
  var btnIdioma = document.getElementById('btn-idioma');
  if (btnIdioma) {
    var spanAtual = btnIdioma.querySelector('.idioma-atual');
    if (spanAtual) {
      var bandeiras = { pt: '🇧🇷', en: '🇺🇸' };
      spanAtual.textContent = bandeiras[lang] + ' ' + lang.toUpperCase();
    }
  }

  // 6) <html lang>
  document.documentElement.lang = lang === 'pt' ? 'pt-BR' : 'en';

  // 7) Placeholder da busca
  var busca = document.getElementById('busca-caso');
  if (busca) {
    busca.placeholder = lang === 'pt' ? '🔍 Buscar caso...' : '🔍 Search case...';
  }

  // 8) Aviso de idioma no console
  console.log('✓ Traduções aplicadas: ' + lang.toUpperCase() + ' (' + aplicados + ' elementos)');

  return aplicados;
};

// Função pública para trocar idioma
window.selecionarIdioma = function(novoIdioma) {
  if (novoIdioma !== 'pt' && novoIdioma !== 'en') return false;
  if (novoIdioma === window.idiomaAtual) {
    if (window.fecharModal) window.fecharModal();
    return true;
  }

  window.idiomaAtual = novoIdioma;
  try { localStorage.setItem('arquivoMorto_idioma', novoIdioma); } catch(e) {}

  // 1) Aplica traduções estáticas
  window.aplicarTraducoes();

  // 2) Re-renderiza telas dinâmicas
  if (window.reRenderizarTelasDinamicas) {
    window.reRenderizarTelasDinamicas();
  }

  // 3) Re-renderiza o menu de casos da sidebar
  if (window.renderizarMenu) {
    try { window.renderizarMenu(); } catch(e) {}
  }

  // 4) Re-renderiza o conteúdo principal (home ou caso aberto)
  if (window.renderizarHome) {
    try {
      var contentHome = document.getElementById('content');
      if (contentHome && contentHome.querySelector('.content-intro')) {
        window.renderizarHome();
      }
    } catch(e) {}
  }

  // 5) Se caso aberto, re-renderiza ele
  if (window.renderizarCasoAtual && window.casoAtualRef && window.casoAtualRef()) {
    try { window.renderizarCasoAtual(); } catch(e) {}
  }

  // 6) Fecha modal se aberto
  if (window.fecharModal) window.fecharModal();

  // 7) Notifica
  if (window.notificar) {
    var bandeiras = { pt: '🇧🇷', en: '🇺🇸' };
    var nomes = { pt: 'Português', en: 'English' };
    window.notificar(
      bandeiras[novoIdioma] + ' ' + nomes[novoIdioma],
      novoIdioma === 'pt' ? 'Idioma alterado' : 'Language changed'
    );
  }

  if (window.tocarSom) window.tocarSom('clique');

  return true;
};

// Aliases para compatibilidade
window.trocarIdioma = function() {
  var proximo = window.idiomaAtual === 'pt' ? 'en' : 'pt';
  return window.selecionarIdioma(proximo);
};

window.aplicarIdiomaV6 = window.selecionarIdioma;

